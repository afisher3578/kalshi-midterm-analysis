import { chromium } from "playwright";
import AxeBuilder from "@axe-core/playwright";
const b = await chromium.launch({ executablePath: process.env.CHROME_PATH });
const ctx = await b.newContext({ viewport: { width: 390, height: 900 } });
const p = await ctx.newPage();
await p.goto("http://127.0.0.1:4173/", { waitUntil: "networkidle" });
await p.waitForSelector("#panel-att-0 svg");
console.log(await p.evaluate(() => [...document.querySelectorAll("*")].filter(e => !e.closest(".table-scroll") && e.getBoundingClientRect().right > 392).map(e => e.tagName + " " + (e.id||"") + " " + (e.textContent||"").slice(0,40) + " " + Math.round(e.getBoundingClientRect().right)).slice(0,20)));
const a = await new AxeBuilder({ page: p }).analyze();
for (const v of a.violations) console.log(v.id, v.nodes.slice(0,3).map(n => n.html.slice(0,200)), v.nodes[0].failureSummary);
await b.close();
